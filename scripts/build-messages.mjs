function withQueues(ui, localeKey, queueData) {
  const q = queueData[localeKey]
  if (!q) throw new Error(`Missing queue data for ${localeKey}`)
  const table = { ...ui }
  for (const [msgKey, jsonKey] of Object.entries(QUEUE_JSON_KEYS)) {
    table[msgKey] = q[jsonKey]
  }
  return table
}

function escapeTs(s) {
  return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")
}

function formatConst(name, table) {
  const lines = MESSAGE_KEYS.map((key) => `  '${key}': '${escapeTs(table[key])}',`)
  return `const ${name}: MessageTable = {\r\n${lines.join('\r\n')}\r\n}`
}

function tablesEqual(a, b) {
  return MESSAGE_KEYS.every((key) => a[key] === b[key])
}

